const express = require('express')
const authFinalMiddleware = require('../middleware/authFinalMiddleware')
const inventoryController = require('../controllers/inventory.controller')
const inventoryV2 = require('../inventory/inventory.controller')

const router = express.Router()

router.use(authFinalMiddleware)

// Inventory V2 foundation. V1 routes below remain connected during the staged cutover.
router.get('/capabilities', inventoryV2.capabilities)
router.get('/summary', inventoryV2.summary)
router.get('/catalog/search', inventoryV2.catalogSearch)
router.get('/catalog/discovery', inventoryV2.catalogDiscovery)
router.get('/locations', inventoryV2.locationsList)
router.post('/locations', inventoryV2.locationsCreate)
router.patch('/locations/:id', inventoryV2.locationsEdit)
router.delete('/locations/:id', inventoryV2.locationsDelete)
router.post('/locations/reorder', inventoryV2.locationsReorder)
router.post('/locations/:id/move-products', inventoryV2.locationsMoveProducts)
router.get('/products', inventoryV2.productsList)
router.post('/products', inventoryV2.productsCreate)
router.post('/products/batch', inventoryV2.productsBatch)
router.get('/products/:id', inventoryV2.productsGet)
router.patch('/products/:id', inventoryV2.productsEdit)
router.post('/products/:id/quantity-adjust', inventoryV2.productsAdjust)
router.post('/products/:id/quantity-set', inventoryV2.productsSet)
router.post('/products/:id/archive', inventoryV2.productsArchive)
router.post('/products/:id/restore', inventoryV2.productsRestore)
router.post('/products/:id/trash', inventoryV2.productsTrash)
router.post('/products/:id/restore-from-trash', inventoryV2.productsRestoreTrash)
router.delete('/products/:id/permanent', inventoryV2.productsPermanent)

router.get('/templates', inventoryController.listTemplates)
router.get('/items', inventoryController.listItems)
router.post('/items', inventoryController.createItem)
router.patch('/items/:item_id', inventoryController.updateItem)
router.delete('/items/:item_id', inventoryController.deleteItem)
router.post('/items/:item_id/add', inventoryController.addQuantity)
router.post('/items/:item_id/consume', inventoryController.consumeQuantity)
router.post('/items/:item_id/out-of-stock', inventoryController.markOutOfStock)
router.get('/alerts', inventoryController.getAlerts)
router.get('/restock-requests', inventoryController.listRestockRequests)
router.post('/restock-requests/:request_id/approve', inventoryController.approveRestockRequest)
router.post('/restock-requests/:request_id/reject', inventoryController.rejectRestockRequest)

module.exports = router
